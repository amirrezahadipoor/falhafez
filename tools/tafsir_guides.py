def build_bank():
    """بانکِ نهایی: جمله‌های قبلی + جمله‌های تازه."""
    bank = {}
    for theme, items in OLD_GUIDE.items():
        bank[theme] = list(items) + EXTRA.get(theme, [])
    for theme, items in EXTRA.items():
        bank.setdefault(theme, list(items))
    return bank


