def theme_of(p):
    """
    تمِ بانک را تعیین می‌کند.

    اولویت با مفهومِ غالبِ خودِ شعر است؛ اگر مفهومی تشخیص داده نشد، به
    برچسبِ `themeTag` و در نهایت به `general` برمی‌گردیم.
    """
    c = concept_of(p)
    if c:
        mapped = CONCEPT_TO_THEME.get(c)
        if mapped and mapped in BANK:
            return mapped
    t = (p.get("themeTag") or "general").strip()
    return t if t in BANK else "general"


def respread(p, rnd):
    """
    اگر جملهٔ پایانی از بانکِ قدیمی است، با گزینه‌ای از بانکِ گسترده
    جایگزینش می‌کند. اگر تفسیر ساختارِ «پیوند: پند» ندارد، دست نمی‌خورد.
    """
    t = (p.get("tafsir") or "").strip()
    m = _TAIL.search(t)
    if not m:
        return None
    guide = m.group("guide").strip()
    # هر جمله‌ای که از بانک آمده باشد (قدیمی یا تازه) قابلِ بازپخش است؛
    # محدود کردن به بانکِ قدیمی باعث می‌شد اجرای دوم فقط بخشِ کوچکی را
    # لمس کند و تمِ ریزدانه هرگز روی بقیه اعمال نشود.
    if guide not in ALL_GUIDES:
        return None
    options = BANK.get(theme_of(p)) or BANK["general"]
    new_guide = rnd.choice(options)
    if new_guide == guide:
        return None
    out = t[: m.start("guide")] + new_guide
    if out and out[-1] not in TERMINALS:
        out += "."
    return out


def main():
    dry = "--dry" in sys.argv
    total = 0
    for name in FILES:
        path = os.path.join(CORPUS, name + ".dat")
        with gzip.open(path, "rt", encoding="utf-8") as f:
            poems = json.load(f)
        n = 0
        for p in poems:
            rnd = random.Random(p["id"] * 2654435761)
            new = respread(p, rnd)
            if new:
                p["tafsir"] = new
                n += 1
        total += n
        if n and not dry:
            with gzip.open(path, "wt", encoding="utf-8") as f:
                json.dump(poems, f, ensure_ascii=False)
        print(f"  {name}: {n} پندِ بازپخش‌شده")
    sizes = {k: len(v) for k, v in BANK.items()}
    print(f"اندازهٔ بانک: {sizes}")
    print(f"{'(آزمایشی) ' if dry else ''}مجموع: {total}")


if __name__ == "__main__":
    main()
