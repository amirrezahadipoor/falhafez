def build():
    with gzip.open(PATH, "rt", encoding="utf-8") as f:
        data = json.load(f)

    existing_titles = {
        p["verses"][0]["first"].split("\n\n")[0].strip() for p in data
    }
    start_id = max(p["id"] for p in data)
    start_num = max(p["number"] for p in data)

    assert len(NEW) == len(TAFSIR), f"{len(NEW)} مطلب ولی {len(TAFSIR)} تفسیر"

    added = []
    for i, ((theme, title, body, key, source), tafsir) in enumerate(zip(NEW, TAFSIR)):
        if title in existing_titles:
            raise SystemExit(f"عنوانِ تکراری: {title}")
        added.append({
            "id": start_id + 1 + i,
            "poet": "world",
            "collection": "stories",
            "number": start_num + 1 + i,
            "themeTag": theme,
            "tafsir": tafsir,
            "verses": [
                {"first": f"{title}\n\n{body}", "second": None, "meaning": None},
                {"first": key, "second": source, "meaning": None},
            ],
        })

    data.extend(added)
    with gzip.open(PATH, "wt", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False)

    print(f"مطالبِ تازه: {len(added)}   مجموع: {len(data)}")
    from collections import Counter
    print("تم‌ها:", dict(Counter(p["themeTag"] for p in data)))


if __name__ == "__main__":
    build()
