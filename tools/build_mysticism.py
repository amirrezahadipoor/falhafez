def build():
    poems = []
    for it in ITEMS:
        pid = 9000000 + it["n"]
        body = "\n\n".join(it["body"])
        poems.append({
            "id": pid,
            "poet": "saadi",
            "collection": "stories",
            "number": it["n"],
            "themeTag": it["tag"],
            "tafsir": it["tafsir"],
            "verses": [
                {"first": it["title"] + "\n\n" + body, "second": None, "meaning": None},
                {"first": it["key"], "second": it["source"], "meaning": None},
            ],
        })
    path = "app/src/main/assets/corpus/stories.dat"
    gzip.open(path, "wt", encoding="utf-8").write(
        json.dumps(poems, ensure_ascii=False, separators=(",", ":"))
    )
    print(f"stories.dat rebuilt: {len(poems)} items")

if __name__ == "__main__":
    build()
