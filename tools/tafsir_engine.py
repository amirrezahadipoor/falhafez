def sanitize_output(s):
    """
    آخرین سدّ کیفیت. حتی اگر شرحِ ورودی الگوی عجیبی داشته باشد، متنِ نهایی
    نباید نویزِ ویرایشی به کاربر نشان دهد.
    """
    s = s or ""
    # بازماندهٔ «منبع: …» در هر جای متن
    s = re.sub(r"\s*[-–—]?\s*منبع\s*[:：][^.!؟…]*", " ", s)
    # هر قلابِ باقی‌مانده
    s = re.sub(r"\[[^\]]*\]?", " ", s)
    s = s.replace("]", " ")
    # پرانتز/گیومهٔ نامتوازن را می‌بندیم یا حذف می‌کنیم
    for op, cl in (("(", ")"), ("«", "»")):
        while s.count(op) > s.count(cl):
            i = s.rfind(op)
            j = s.find(".", i)
            s = s[:i] + (s[j:] if j != -1 else "")
        while s.count(cl) > s.count(op):
            s = s.replace(cl, " ", 1)
    s = re.sub(r"\(\s*\)|«\s*»", " ", s)
    s = re.sub(r"\s+", " ", s)
    s = re.sub(r"\s+([.،؛:!؟])", r"\1", s)
    s = re.sub(r"([.!؟…])[\s]*([.!؟])", r"\1", s)
    return s.strip()


def build_tafsir(poem):
    verses = poem.get("verses") or []
    if not verses:
        return None

    poet = poem.get("poet", "hafez")
    coll = poem.get("collection", "ghazal")
    form = FORM_FA.get(coll, "شعر")

    poem_text = " ".join(
        (v.get("first") or "") + " " + (v.get("second") or "") + " " + (v.get("meaning") or "")
        for v in verses
    )

    theme = detect_theme(poem_text, poem.get("themeTag"))
    motifs = detect_motifs(poem_text)
    motif_label = motifs[0][1] if motifs else None

    # بذر بر پایهٔ شناسهٔ شعر → خروجی پایدار و بازتولیدپذیر، ولی متنوع
    rnd = random.Random(f"{poet}:{coll}:{poem.get('id')}:{poem.get('number')}")

    fv = focal_verse(verses)
    core = first_sentences(clean_meaning(fv.get("meaning") if fv else ""), max_len=175)
    core = ensure_period(core) if core else ""

    opener = rnd.choice(OPENERS)
    voice = voice_of(poet, form, motif_label, rnd)
    bridge = rnd.choice(BRIDGES)
    closer = rnd.choice(CLOSERS.get(theme, CLOSERS["wisdom"]))

    # چینشِ جمله‌ها متغیر است تا ریتمِ متن یکنواخت نشود
    shape = rnd.randint(0, 2)
    if not core:
        body = join_sentence(join_sentence(opener, voice), closer)
    elif shape == 0:
        body = join_sentence(opener + ": " + voice + ".", core)
        body = join_sentence(body, bridge + ": " + closer)
    elif shape == 1:
        body = join_sentence(voice + ".", core)
        body = join_sentence(body, opener + "؛ " + bridge + ": " + closer)
    else:
        body = join_sentence(join_sentence(opener, core), closer)

    # پاک‌سازیِ نهایی
    body = sanitize_output(body)
    body = re.sub(r"\s+", " ", body).strip()
    body = re.sub(r"\s+([.،؛:!؟])", r"\1", body)     # فاصلهٔ پیش از نشانه
    body = re.sub(r"([.!؟…])\s*\1+", r"\1", body)    # نشانهٔ تکراری
    body = re.sub(r"[.]{2,}", ".", body)
    body = body.replace("!.", "!").replace("؟.", "؟").replace("….", "…")
    body = re.sub(r":\s*:", ":", body)
    return ensure_period(body), theme


