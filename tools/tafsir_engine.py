def focal_verse(verses):
    """
    بیتی را برمی‌گرداند که بیشترین «پیام» را دارد.

    چرا نه بیتِ اول؟ چون مطلعِ غزل معمولاً تصویری و تغزّلی است («الا یا ایها الساقی»)
    و پندِ فال بیشتر در بیت‌های میانی یا مقطع می‌نشیند. استفادهٔ همیشگی از بیتِ اول
    دقیقاً همان چیزی بود که ۷۱٪ تفسیرها را شبیهِ هم کرده بود.
    """
    best, best_score = None, -1.0
    n = len(verses)
    for i, v in enumerate(verses):
        m = clean_meaning(v.get("meaning"))
        if len(m) < 30:
            continue
        text = strip_diacritics((v.get("first") or "") + " " + (v.get("second") or "") + " " + m)
        score = 0.0
        score += 2.2 * len(_SIGNAL.findall(text))
        score += min(len(m), 260) / 120.0          # شرحِ پرمایه‌تر
        if 0 < i < n - 1:
            score += 1.4                            # بیت‌های میانی
        if i == n - 1 and n > 2:
            score += 1.0                            # مقطع اغلب نتیجه‌گیری است
        if i == 0:
            score -= 1.2                            # مطلع را عقب می‌رانیم
        if score > best_score:
            best, best_score = v, score
    if best is None:
        # هیچ شرحِ به‌دردبخوری نبود → بلندترین شرح
        best = max(verses, key=lambda v: len(clean_meaning(v.get("meaning"))), default=None)
    return best


