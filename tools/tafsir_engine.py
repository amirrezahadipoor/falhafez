# واژه‌هایی که در فارسی پرکاربردند و اگر «زیررشته‌ای» تطبیق داده شوند، تم را منحرف می‌کنند.
# نمونهٔ واقعی: «می» با پیشوندِ فعلیِ «می‌رود» یکی گرفته می‌شد و همهٔ فال‌ها «شادی» می‌شدند.
_TOKEN_RX = re.compile(r"[^\u0600-\u06FF\u200c]+")

def tokenize(text):
    """متن را به مجموعهٔ واژه تبدیل می‌کند (بدون اعراب، بدون نیم‌فاصله)."""
    t = strip_diacritics(normalize(text)).replace(ZWNJ, " ")
    return [w for w in _TOKEN_RX.split(t) if w]


# پیشوند/پسوندهای صرفی که باید پیش از تطبیق کنار بروند
_AFFIX_PRE = ("می", "نمی", "بی", "با", "به", "در", "از")
_AFFIX_SUF = ("ها", "های", "هایی", "ان", "ات", "اش", "ام", "یم", "ید", "ند",
              "تر", "ترین", "ی", "را", "ست", "است")

def stems(word):
    """ریشه‌های محتملِ یک واژه — برای تطبیقِ «عاشقان» با «عاشق»."""
    out = {word}
    for suf in _AFFIX_SUF:
        if len(word) > len(suf) + 2 and word.endswith(suf):
            out.add(word[: -len(suf)])
    return out


def build_index(word_lists):
    """نگاشتِ واژه → کلید. فقط تطبیقِ کاملِ واژه (نه زیررشته)."""
    idx = {}
    for key, words in word_lists:
        for w in words:
            w = strip_diacritics(normalize(w)).replace(ZWNJ, " ").strip()
            if not w:
                continue
            if " " in w:                      # عبارتِ چندواژه‌ای
                idx.setdefault(w, set()).add(key)
            else:
                idx.setdefault(w, set()).add(key)
    return idx


_THEME_INDEX = build_index([(k, v["words"]) for k, v in THEMES.items()])
_THEME_PHRASES = {w: ks for w, ks in _THEME_INDEX.items() if " " in w}


def _score_index(text, index, phrases):
    """شمارشِ برخوردها با تطبیقِ واژه‌ایِ دقیق + عباراتِ چندواژه‌ای."""
    toks = tokenize(text)
    scores = Counter()
    seen_words = Counter()
    for w in toks:
        for st in stems(w):
            for key in index.get(st, ()):
                # هر واژه حداکثر ۳ بار امتیاز می‌دهد؛ تکرارِ یک کلمه نباید تم را برباید
                if seen_words[(key, st)] < 3:
                    seen_words[(key, st)] += 1
                    scores[key] += 1
    flat = " ".join(toks)
    for phrase, keys in phrases.items():
        n = flat.count(phrase)
        if n:
            for key in keys:
                scores[key] += min(n, 3)
    return scores


def detect_theme(poem_text, fallback):
    """
    تمِ غالب را از متنِ ابیات (و نه از تگِ قبلی) می‌یابد.

    تگ‌های قبلی به‌شدت پرت بودند: ۲٬۴۴۹ شعر «صبر» و تنها ۲ شعر «مهربانی».
    اینجا واژگانِ خودِ شعر رأی می‌دهند.
    """
    scores = _score_index(poem_text, _THEME_INDEX, _THEME_PHRASES)
    if not scores:
        return fallback if fallback in THEMES else "wisdom"
    # ریشهٔ دوم: شعرِ بلند نباید صرفاً به‌خاطر طولش یک تم را غالب کند
    adj = {k: v ** 0.7 for k, v in scores.items()}
    top = max(adj, key=adj.get)
    best = adj[top]
    # اگر تگِ قبلی امتیازِ نزدیکی دارد، به آن وفادار می‌مانیم (احترام به کارِ دستی)
    if fallback in adj and adj[fallback] >= best * 0.9:
        return fallback
    return top


