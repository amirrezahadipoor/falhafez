ZWNJ = "\u200c"

def normalize(s):
    """یکسان‌سازیِ نویسه‌های عربی/فارسی و فاصله‌ها."""
    if not s:
        return ""
    s = unicodedata.normalize("NFC", s)
    s = s.replace("ي", "ی").replace("ك", "ک").replace("ۀ", "ه" + ZWNJ)
    s = s.replace("\u064a", "ی").replace("\u0643", "ک")
    s = re.sub(r"[ \t]+", " ", s)
    return s.strip()


def strip_diacritics(s):
    """حذفِ اعراب — فقط برای تطبیقِ واژگان، نه برای نمایش."""
    return re.sub(r"[\u064B-\u0652\u0670\u0640]", "", s or "")


# الگوهای نویز در شرح‌های برگرفته از گنجور
_NOISE = [
    re.compile(r"\s*[-–—]?\s*منبع\s*[:：].*$", re.S),        # «منبع: شرح غزل‌های سعدی»
    re.compile(r"\(\s*نکته\s*[۰-۹0-9]*\s*[:：].*?\)", re.S),  # «(نکته ۱: …)»
    re.compile(r"\s*نکته\s*[۰-۹0-9]*\s*[:：].*$", re.S),
    re.compile(r"\[[^\]]{0,200}\]"),                          # قلابِ کامل
    re.compile(r"«\s*»"),
    re.compile(r"\s*/\s*یا\s*/.*$", re.S),                    # «/یا/ روایتِ دوم…»
]

# قلاب یا پرانتزی که **باز شده و بسته نشده** — در شرح‌های گنجور فراوان است و
# اگر فقط الگوی «کاملِ» بالا را بزنیم، دنبالهٔ واژه‌نامه‌ای در متن باقی می‌ماند.
_UNCLOSED = [("[", "]"), ("(", ")"), ("«", "»")]

def _drop_unclosed(s):
    for op, cl in _UNCLOSED:
        i = s.rfind(op)
        if i != -1 and s.find(cl, i) == -1:
            s = s[:i]
    return s

def clean_meaning(m):
    """شرحِ بیت را به یک جملهٔ خوانا و بی‌نویز تبدیل می‌کند."""
    s = normalize(m)
    if not s:
        return ""
    for pat in _NOISE:
        s = pat.sub(" ", s)
    s = _drop_unclosed(s)
    s = re.sub(r"\(\s*\)", " ", s)
    s = re.sub(r"\s+", " ", s).strip(" .،؛:-—–")
    return s


_SENT_END = re.compile(r"[.!؟?؛]")

def first_sentences(s, max_len=170):
    """
    تا سقفِ [max_len] نویسه، جمله‌های کامل برمی‌گرداند.
    هرگز وسطِ جمله یا کلمه نمی‌بُرد — ریشهٔ ۲٬۳۲۱ شرحِ نصفه‌کاره همین بود.
    """
    s = (s or "").strip()
    if not s:
        return ""
    if len(s) <= max_len:
        return s.rstrip(" ،؛:-")

    # مرزهای جمله
    cuts = [m.end() for m in _SENT_END.finditer(s) if m.end() <= max_len]
    if cuts:
        return s[: cuts[-1]].strip().rstrip("؛,،")

    # مرزِ نیم‌جمله
    for sep in ("؛", "،", " و "):
        idx = s.rfind(sep, 0, max_len)
        if idx > max_len * 0.45:
            return s[:idx].strip().rstrip("؛,، و")

    # مرزِ کلمه
    idx = s.rfind(" ", 0, max_len)
    return (s[:idx] if idx > 0 else s[:max_len]).strip().rstrip("؛,،") + "…"


def ensure_period(s):
    s = (s or "").strip()
    if not s:
        return ""
    return s if s[-1] in ".!؟?…" else s + "."


