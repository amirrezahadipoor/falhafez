_MOTIF_MIN_HITS = 2

def detect_motifs(poem_text, limit=2):
    scores = _score_index(poem_text, _MOTIF_INDEX, _MOTIF_PHRASES)
    strong = [(n, k) for k, n in scores.items() if n >= _MOTIF_MIN_HITS]
    strong.sort(reverse=True)
    return [(k, _MOTIF_LABEL[k]) for _, k in strong[:limit]]


