def voice_of(poet, form, motif_label, rnd):
    """
    جملهٔ معرفیِ کوتاه.
    اگر شعر نقش‌مایهٔ روشنی نداشته باشد، جملهٔ بدونِ نقش‌مایه ساخته می‌شود —
    نه عبارتِ بی‌معنیِ «بی‌واسطه».
    """
    p = POET_FA.get(poet, "شاعر")
    if motif_label:
        variants = [
            f"{p} در این {form} {motif_label} با تو سخن می‌گوید",
            f"{p} این {form} را {motif_label} بسته است",
            f"در این {form}، {p} {motif_label} پرده برمی‌دارد",
            f"{p} اینجا {motif_label} حرفش را می‌زند",
        ]
    else:
        variants = [
            f"{p} در این {form} بی‌پرده با تو سخن می‌گوید",
            f"{p} این {form} را ساده و روشن گفته است",
            f"در این {form}، {p} یک‌راست سرِ اصلِ مطلب می‌رود",
            f"{p} اینجا حرفش را بی‌مقدمه می‌زند",
        ]
    return rnd.choice(variants)


# نویسه‌های پایانِ جمله — برای جلوگیری از «..» و «.:» در چسباندنِ جمله‌ها
_TERMINALS = ".!؟?…"

def join_sentence(head, tail, sep=". "):
    """
    دو پاره را می‌چسباند بدون آنکه نقطه‌گذاری دوتایی بسازد.
    (خروجیِ اولیه جمله‌هایی مثل «…فراموش می‌شوند!. به‌جای آنکه…» تولید می‌کرد.)
    """
    head = (head or "").strip()
    tail = (tail or "").strip()
    if not head:
        return tail
    if not tail:
        return head
    if head[-1] in _TERMINALS:
        # پایان‌بندی از قبل هست → فقط یک فاصله
        return head + " " + tail
    if head[-1] in "،؛:":
        return head + " " + tail
    return head + sep + tail


