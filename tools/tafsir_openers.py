# آستانه بر پایهٔ طولِ شعر: رباعیِ چهار مصراعی هرگز سه بار یک واژه را
# تکرار نمی‌کند، پس آستانهٔ ثابتِ ۳ عملاً همهٔ رباعی‌ها را رد می‌کرد و
# آن‌ها روی گشایشِ قالبی می‌ماندند (۱٬۱۷۴ رباعیِ مولانا).
CONCEPT_MIN_HITS = 3
CONCEPT_MIN_HITS_SHORT = 2
SHORT_VERSE_COUNT = 4

OPEN_TOPIC = [
    "{p} در این {f} از {w} می‌گوید",
    "{p} این {f} را حولِ {w} بسته است",
    "در این {f}، سخنِ {p} بر سرِ {w} است",
    "{p} در این {f} سراغِ {w} می‌رود",
    "محورِ این {f}، {w} است",
    "{p} در این {f} با {w} کار دارد",
    "این {f} از {p} دربارهٔ {w} است",
    "{p} در این {f} به {w} می‌پردازد",
]

_TOKEN = re.compile(r"[^\u0600-\u06FF\u200c]+")


def words(text):
    for w in _TOKEN.split(strip_diacritics(text or "")):
        w = w.strip("\u200c")
        if len(w) >= MIN_WORD_LEN and w not in STOP:
            yield w


def poem_text(p):
    return " ".join(
        (v.get("first") or "") + " " + (v.get("second") or "")
        for v in (p.get("verses") or [])
    )


def concept_of(p):
    """
    پربسامدترین مفهومِ شعر بر پایهٔ فرهنگِ دستی.

    آستانهٔ `CONCEPT_MIN_HITS` جلوی برچسب‌زدن بر پایهٔ یک اشارهٔ گذرا را
    می‌گیرد؛ مفهوم باید واقعاً در شعر حضور داشته باشد.
    """
    text = " " + strip_diacritics(poem_text(p)) + " "
    best, best_hits = None, 0
    for label, keys in CONCEPTS:
        hits = 0
        for k in keys:
            hits += text.count(" " + k) + text.count(k + " ")
        if hits > best_hits:
            best, best_hits = label, hits
    n_verses = len(p.get("verses") or [])
    floor = CONCEPT_MIN_HITS_SHORT if n_verses <= SHORT_VERSE_COUNT else CONCEPT_MIN_HITS
    return best if best_hits >= floor else None


# گشایش‌هایی که خودِ این ابزار ساخته است — تا با به‌روزشدنِ فرهنگِ مفاهیم
# بتوان دوباره و دقیق‌تر بازنویسی‌شان کرد.
_OWN = re.compile(
    r"^(?:.{1,12} در این .{1,18} (?:از|به|با|سراغِ)|"
    r"در این .{1,18}، سخنِ|محورِ این|این .{1,18} از .{1,12} دربارهٔ|"
    r".{1,12} این .{1,18} را حولِ)"
)


def is_generic(tafsir):
    head = (tafsir or "").split(".", 1)[0]
    if any(g in head for g in GENERIC):
        return True
    return bool(_OWN.match(head.strip()))


def rewrite(p, rnd):
    t = p.get("tafsir") or ""
    if not is_generic(t):
        return None
    w = concept_of(p)
    if not w:
        return None
    poet = POET_FA.get(p.get("poet"), "شاعر")
    form = FORM_FA.get(p.get("collection"), "سروده")
    opener = rnd.choice(OPEN_TOPIC).format(p=poet, f=form, w=w)
    rest = t.split(".", 1)[1].strip() if "." in t else ""
    out = f"{opener}. {rest}".strip()
    if out and out[-1] not in TERMINALS:
        out += "."
    return out


def main():
    dry = "--dry" in sys.argv
    changed = 0
    for name in FILES:
        path = os.path.join(CORPUS, name + ".dat")
        with gzip.open(path, "rt", encoding="utf-8") as f:
            poems = json.load(f)
        n = 0
        for p in poems:
            rnd = random.Random(p["id"] * 15485863)
            new = rewrite(p, rnd)
            if new:
                p["tafsir"] = new
                n += 1
        changed += n
        if n and not dry:
            with gzip.open(path, "wt", encoding="utf-8") as f:
                json.dump(poems, f, ensure_ascii=False)
        print(f"  {name}: {n} گشایشِ بازنویسی‌شده")
    print(f"{'(آزمایشی) ' if dry else ''}مجموع: {changed}")


if __name__ == "__main__":
    main()
