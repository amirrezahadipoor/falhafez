"""
عمیق‌ترکردنِ تفسیرها — گره‌زدنِ متن به خودِ شعر به‌جای بانکِ جمله‌های آماده.

مسئله
-----
`tafsir_engine.py` هر تفسیر را از یک بانکِ ثابت می‌ساخت: یک «گشایش» از دوازده
گزینه، یک «پند» از میانِ چند گزینه برای هر یک از نُه تم. چون تعدادِ اشعار
هزاران برابرِ تعدادِ قالب‌هاست، جمله‌ها ناگزیر تکرار می‌شدند:

    حافظ  ۴۵٪ | سعدی ۵۰٪ | مولانا ۵۴٪ | خیام ۵۷٪
    (سهمِ نمونه‌جمله‌هایی که دستِ‌کم دو بار در پیکره آمده‌اند)

سنجه‌های `validate_content.py` این را نمی‌گرفتند، چون آن‌ها تکرارِ *کلِ متنِ
تفسیر* را می‌سنجند و هر تفسیر دستِ‌کم در یک جمله با بقیه فرق داشت. اما برای
خواننده‌ای که چند فال پشتِ سرِ هم می‌گیرد، تکرار کاملاً محسوس است.

راهکار
------
بدنهٔ تفسیر از **شرحِ واقعیِ ابیاتِ همان شعر** ساخته می‌شود، نه از بانکِ
جمله‌ها. برای هر شعر:

۱. دو بیتِ کلیدی انتخاب می‌شود — یکی «تصویر» (بیتی که صحنه را می‌سازد) و
   یکی «پیام» (بیتی که بیشترین بارِ پندی را دارد، با همان سنجهٔ
   `focal_verse` که پیش‌تر نوشته شده بود).
۲. شرحِ آن دو بیت به نثرِ روان بازنویسی می‌شود: فعل‌های شرحِ سومِ‌شخص به
   خطابِ دومِ‌شخص برمی‌گردد و به هم پیوند می‌خورد.
۳. تنها **یک** جمله از بانکِ پند می‌آید و آن هم بر پایهٔ ترکیبِ
   (تم × نقش‌مایه × شناسهٔ شعر) انتخاب می‌شود تا پراکندگی بیشینه شود.

نتیجه: هستهٔ هر تفسیر یکتاست، چون از متنِ یکتای همان غزل می‌آید.

قیدهای حفظ‌شده
--------------
* امانت‌داری: شرحِ اصلی دستکاریِ معنایی نمی‌شود؛ فقط زاویهٔ خطاب عوض می‌شود.
* هیچ تفسیری کوتاه‌تر از ۱۲۰ نویسه نمی‌شود.
* پایان‌بندی همیشه با نویسهٔ پایانِ جمله.
* بخشِ «جهان» (stories) دست‌نخورده می‌مانَد؛ آن‌ها دست‌نویس‌اند.

اجرا:  python3 tools/tafsir_deepen.py [--dry]
"""

