OPEN_WITH_POET = [
    "{p} در این {f} از {m} می‌گوید",
    "{p} این {f} را {m} بسته است",
    "در این {f}، {p} {m} سخن می‌گوید",
]

OPEN_PLAIN = [
    "{p} در این {f} یک‌راست سرِ اصلِ مطلب می‌رود",
    "{p} این {f} را ساده و روشن گفته است",
    "{p} در این {f} بی‌مقدمه حرفش را می‌زند",
]


def build_tafsir(poem, rnd):
    verses = poem.get("verses") or []
    head, msg = pick_pair(verses)
    if msg is None:
        return None

    poet = POET_FA.get(poem.get("poet"), "شاعر")
    form = FORM_FA.get(poem.get("collection"), "سروده")

    text = " ".join(
        strip_diacritics((v.get("first") or "") + " " + (v.get("second") or ""))
        for v in verses
    )
    theme = detect_theme(text, poem.get("themeTag") or "general")
    motifs = detect_motifs(text, limit=1)
    motif = _MOTIF_LABEL.get(motifs[0]) if motifs else None

    if motif:
        opener = rnd.choice(OPEN_WITH_POET).format(p=poet, f=form, m=motif)
    else:
        opener = rnd.choice(OPEN_PLAIN).format(p=poet, f=form)

    body_head = humanize(head.get("meaning")) if head is not None else ""
    body_msg = humanize(msg.get("meaning"))
    if not body_msg:
        return None

    # هستهٔ یکتا: شرحِ واقعیِ ابیاتِ همین شعر.
    # هر پاره جداگانه نقطه‌گذاری می‌شود تا دو شرح در هم نروند
    # («…سخت شد از بس گرفتار…» حاصلِ همین چسباندنِ بی‌نقطه بود).
    core = terminate(clip(body_msg, 240))
    if body_head and len(core) < 165:
        head_txt = clip(body_head, 150)
        # فقط وقتی بیتِ تصویری را می‌افزاییم که خودش جملهٔ کاملی باشد
        if len(head_txt) <= 150:
            core = terminate(head_txt) + " " + core

    bridge = rnd.choice(BRIDGE)
    guide = rnd.choice(GUIDE.get(theme, GUIDE["general"]))

    parts = [terminate(opener), core, f"{bridge}: {guide}"]
    out = " ".join(p.strip() for p in parts if p.strip())
    out = re.sub(r"\s+", " ", out).strip()
    out = out.replace(" .", ".").replace("..", ".").replace(".:", ":")
    if out and out[-1] not in TERMINALS:
        out += "."
    return out if len(out) >= MIN_LEN else None


def main():
    dry = "--dry" in sys.argv
    total = changed = 0
    for name in FILES:
        path = os.path.join(CORPUS, name + ".dat")
        with gzip.open(path, "rt", encoding="utf-8") as f:
            poems = json.load(f)
        for p in poems:
            total += 1
            # بذر بر پایهٔ شناسه → خروجی پایدار و تکرارپذیر
            rnd = random.Random(p["id"] * 7919)
            new = build_tafsir(p, rnd)
            if new and new != p.get("tafsir"):
                p["tafsir"] = new
                changed += 1
        if not dry:
            with gzip.open(path, "wt", encoding="utf-8") as f:
                json.dump(poems, f, ensure_ascii=False)
        print(f"  {name}: {len(poems)} شعر")
    print(f"{'(آزمایشی) ' if dry else ''}بازنویسی‌شده: {changed} از {total}")


if __name__ == "__main__":
    main()
