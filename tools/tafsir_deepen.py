# شرح‌های گنجور با فعلِ سومِ‌شخص نوشته شده‌اند («می‌گوید که…»).
# برای آنکه تفسیر با خواننده حرف بزند، تنها الگوهای مطمئن را برمی‌گردانیم.
# هر الگویی که ابهام بیافریند عمداً کنار گذاشته شده تا معنا تحریف نشود.
_ADDRESS = [
    (r"\bشاعر می‌گوید\b", "این بیت می‌گوید"),
    (r"\bمی‌گوید که\b", "می‌گوید"),
    (r"\bیعنی اینکه\b", "یعنی"),
    (r"\bدر این بیت\b", "اینجا"),
    (r"\bاین بیت به این معناست که\b", "یعنی"),
]

_TIDY = [
    (r"\s+", " "),
    (r"\s*([،؛,])\s*", r"\1 "),
    (r"\s*\.\s*\.", "."),
    (r"«\s+", "«"),
    (r"\s+»", "»"),
]


def humanize(meaning):
    """شرحِ خام را به نثرِ روان و بی‌نویز تبدیل می‌کند (بدونِ تغییرِ معنا)."""
    m = clean_meaning(meaning or "")
    if not m:
        return ""
    for rx, rep in _ADDRESS:
        m = re.sub(rx, rep, m)
    for rx, rep in _TIDY:
        m = re.sub(rx, rep, m)
    m = m.strip()
    # حذفِ جمله‌های ناتمامِ انتهایی
    if m and m[-1] not in TERMINALS:
        cut = max(m.rfind(c) for c in TERMINALS)
        if cut > 40:
            m = m[: cut + 1]
    return m.strip()


def clip(text, limit):
    """
    کوتاه‌کردن **فقط** روی مرزِ جمله.

    نسخهٔ اولِ این تابع در نبودِ مرزِ جمله، متن را وسطِ عبارت می‌برید و «…»
    می‌گذاشت. حاصلش جمله‌های ناتمامی مثل «چون مأموران و…» بود. حالا اگر مرزِ
    جملهٔ مناسبی پیدا نشود، متن دست‌نخورده برمی‌گردد و تصمیمِ استفاده یا
    نکردنش با فراخوان است.
    """
    text = text.strip()
    if len(text) <= limit:
        return text if _balanced(text) else _to_balanced_cut(text)
    # مرزهای جمله را از دورترین به نزدیک‌ترین امتحان می‌کنیم و اولین برشی را
    # می‌پذیریم که پرانتز/گیومه را نصفه رها نکند. بدونِ این بررسی، برش‌هایی
    # مثل «…(انبانه یعنی کیسه چرمی» تولید می‌شد که پرانتزش هرگز بسته نمی‌شد.
    cuts = sorted({text.rfind(c, 0, limit) for c in TERMINALS} - {-1}, reverse=True)
    for cut in cuts:
        if cut > 60:
            cand = text[: cut + 1].strip()
            if _balanced(cand):
                return cand
    return _to_balanced_cut(text)


_PAIRS = (("(", ")"), ("«", "»"), ("[", "]"))


def _balanced(s):
    return all(s.count(a) == s.count(b) for a, b in _PAIRS)


def _to_balanced_cut(s):
    """آخرین برشِ ممکن که همهٔ جفت‌ها در آن بسته باشند."""
    for cut in range(len(s), 60, -1):
        if cut < len(s) and s[cut - 1] not in TERMINALS:
            continue
        cand = s[:cut].strip()
        if _balanced(cand):
            return cand
    return re.sub(r"[()«»\[\]]", "", s).strip()


def terminate(text):
    """تضمینِ نقطهٔ پایان تا جمله‌ها هنگامِ چسباندن در هم نروند."""
    text = (text or "").strip()
    if text and text[-1] not in TERMINALS:
        text += "."
    return text


