def pick_pair(verses):
    """
    بیتِ پیام‌دار (با سنجهٔ focal_verse) و یک بیتِ تصویریِ متفاوت.

    بیتِ تصویری از نیمهٔ اولِ شعر و با شرحِ به‌اندازه انتخاب می‌شود تا
    تفسیر با صحنه شروع شود و با پیام تمام.
    """
    usable = [v for v in verses if len(clean_meaning(v.get("meaning"))) >= 40]
    if not usable:
        return None, None
    msg = focal_verse(usable) or usable[-1]
    head = None
    for v in usable:
        if v is msg:
            continue
        head = v
        break
    return head, msg


