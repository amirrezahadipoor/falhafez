CLOSERS = ["با آرامش قدم بردار.", "به دلِ خود اعتماد کن.", "نیک‌اندیش باش."]

def gen(pid, tag, full):
    theme = THEME_NAME[tag]
    opener = f"حافظ در این غزل از {theme} می‌گوید."
    motif = motif_sentence(full)
    msg = MESSAGES[tag][pid % len(MESSAGES[tag])]
    closer = CLOSERS[(pid // 3) % len(CLOSERS)]
    return f"{opener} {motif} {msg} {closer}"

path = "app/src/main/assets/corpus/hafez.dat"
data = json.loads(gzip.open(path, "rt", encoding="utf-8").read())

kept = rewritten = 0
for p in data:
    if is_hand(p):
        kept += 1
        continue
    full = " ".join((v["first"] or "") + " " + (v["second"] or "") for v in p["verses"])
    tag = detect_tag(full)
    p["themeTag"] = tag
    p["tafsir"] = gen(p["id"], tag, full)
    rewritten += 1

with gzip.open(path, "wt", encoding="utf-8") as f:
    json.dump(data, f, ensure_ascii=False, separators=(",", ":"))

lens = [len(p["tafsir"]) for p in data]
print(f"hafez: kept(hand)={kept}, rewritten={rewritten}")
print(f"tafsir length: min={min(lens)}, max={max(lens)}, avg={sum(lens)//len(lens)}")
