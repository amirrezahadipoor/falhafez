package ir.siliksama.falhafez.data.payments

import ir.siliksama.falhafez.BuildConfig

/**
 * کلیدهای پرداختِ درون‌برنامه‌ایِ کافه‌بازار.
 *
 * ## دربارهٔ کلیدِ RSA — چرا «افشا» نیست
 * این کلیدِ **عمومی** (public key) است، نه خصوصی. کارش فقط *راستی‌آزماییِ امضای*
 * رسیدِ خرید است: بازار رسید را با کلیدِ خصوصیِ خودش امضا می‌کند و اپ با این کلیدِ
 * عمومی بررسی می‌کند که رسید جعلی نباشد. طبق طراحیِ Poolakey این کلید باید داخلِ
 * APK باشد و هر کسی که APK را باز کند می‌تواند ببیندش — این در همهٔ اپ‌های بازار
 * (و همین‌طور Google Play) صادق است. دانستنش به کسی اجازهٔ جعلِ رسید نمی‌دهد.
 *
 * پس نگهداریِ آن در مخزن مشکلِ امنیتی نیست. آنچه **هرگز** نباید در مخزن باشد
 * keystore و رمزهای امضای APK است که در این پروژه هم از متغیرهای محیطی خوانده
 * می‌شوند (به `app/build.gradle.kts` نگاه کنید).
 *
 * ## چرا با این حال قابلِ پیکربندی شد
 * دلیلش امنیت نیست، **عملیات** است: هرکس این مخزن را fork کند تا نسخهٔ خودش را
 * منتشر کند، باید کلیدِ برنامهٔ خودش را بگذارد. هاردکد بودن یعنی ویرایشِ کدِ کاتلین
 * و ریسکِ اینکه سهواً کامیت شود. حالا می‌شود بدونِ دست‌زدن به کد، از راهِ
 * `-PbazaarRsaKey=…` یا متغیرِ محیطیِ `BAZAAR_RSA_KEY` مقدار داد.
 *
 * اگر مقداری داده نشود، مقدارِ فعلیِ همین برنامه به‌کار می‌رود.
 *
 * کلید را از پنلِ توسعه‌دهندگانِ کافه‌بازار بگیرید:
 *   پنل ← برنامهٔ شما ← «پرداخت درون‌برنامه‌ای» ← «کلید عمومی (RSA)»
 *
 * اگر خالی بماند، دکمهٔ خرید به‌جای خطا، صفحهٔ برنامه را در بازار باز می‌کند.
 */
object BazaarKeys {

    const val PACKAGE_NAME = "ir.siliksama.falhafez"

    /** کلیدِ عمومیِ RSA — از BuildConfig می‌آید تا در fork ها بدونِ تغییرِ کد عوض شود. */
    val RSA_PUBLIC_KEY: String = BuildConfig.BAZAAR_RSA_KEY
}
