package ir.siliksama.falhafez.domain.usecase

import ir.siliksama.falhafez.domain.model.FalCategory

/**
 * خوانشِ نیّتِ کاربر — تحلیلِ سبکِ متنِ پرسش، کاملاً روی دستگاه و آفلاین.
 *
 * ## چرا؟
 * تا پیش از این، نیّتِ کاربر فقط **نقلِ قول** می‌شد («برای آنچه پرسیدی: …») و بعد
 * متنی کاملاً عمومی می‌آمد. کاربری که نوشته «آیا برگردم یا نه؟» با کاربری که نوشته
 * «کِی حالم بهتر می‌شود؟» دقیقاً یک بستهٔ جملات می‌گرفتند. این همان چیزی است که
 * حسِ «ربات» می‌دهد.
 *
 * اینجا از خودِ متنِ پرسش سه چیز استخراج می‌شود:
 *  • **شکلِ پرسش** — دوراهی؟ زمان‌بندی؟ آری/نه؟ درباره‌ی شخصِ دیگر؟
 *  • **لحن** — نگران، امیدوار، خسته، مردد
 *  • **دسته** — اگر کاربر دسته انتخاب نکرده باشد، از متن حدس زده می‌شود
 *
 * هیچ داده‌ای جایی فرستاده نمی‌شود؛ فقط تطبیقِ واژگانیِ ساده روی رشتهٔ ورودی.
 */
object QuestionInsight {

    /** شکلِ پرسش — تعیین می‌کند تفسیر چطور باید پاسخ بدهد. */
    enum class Shape {
        /** «الف یا ب؟» — کاربر بین دو گزینه مانده. */
        DILEMMA,

        /** «کِی…؟» — پرسش دربارهٔ زمان. */
        TIMING,

        /** «آیا…؟» — انتظارِ آری/نه دارد. */
        YES_NO,

        /** «آیا او…؟» — پرسش دربارهٔ نیّتِ شخصِ دیگر. */
        ABOUT_OTHER,

        /** «چه کنم؟» — درخواستِ راهنمایی. */
        GUIDANCE,

        /** پرسشِ باز یا صرفاً یک نیّت. */
        OPEN
    }

    /** لحنِ عاطفیِ پرسش. */
    enum class Tone { WORRIED, HOPEFUL, WEARY, UNCERTAIN, NEUTRAL }

    data class Insight(
        val shape: Shape,
        val tone: Tone,
        val category: FalCategory,
        /** آیا متنِ پرسش آن‌قدر هست که بشود رویش حساب کرد؟ */
        val meaningful: Boolean
    )

    private const val ZWNJ = '\u200c'

    private fun normalize(s: String): String =
        s.replace('ي', 'ی').replace('ك', 'ک').replace(ZWNJ, ' ')
            .replace(Regex("[\\u064B-\\u0652\\u0670]"), "")
            .replace(Regex("\\s+"), " ")
            .trim()

    private fun has(text: String, vararg words: String) = words.any { text.contains(it) }

    // ── شکلِ پرسش ───────────────────────────────────────────────────────────

    private fun shapeOf(t: String): Shape = when {
        // «یا» بینِ دو گزینه — «بمانم یا بروم»
        Regex("\\S+\\s+یا\\s+\\S+").containsMatchIn(t) ||
            has(t, "کدام", "کدوم", "دوراهی", "دو راه") -> Shape.DILEMMA

        has(t, "کی ", "کی؟", "چه زمان", "چه وقت", "چقدر طول", "تا کی", "زمانش") -> Shape.TIMING

        has(t, "چه کنم", "چیکار", "چکار", "راهنمایی", "چه کار کنم", "چطور",
            "چگونه", "توصیه") -> Shape.GUIDANCE

        // پرسش دربارهٔ شخصِ ثالث
        has(t, "او ", "اون ", "دوستم", "همسرم", "پدرم", "مادرم", "رئیس",
            "شریک", "طرف مقابل", "دوست دارد", "دوستم دارد", "برمیگردد",
            "برمی گردد") &&
            has(t, "آیا", "؟", "می", "دارد") -> Shape.ABOUT_OTHER

        has(t, "آیا", "ایا") || t.endsWith("؟") -> Shape.YES_NO

        else -> Shape.OPEN
    }

    // ── لحن ─────────────────────────────────────────────────────────────────

    private fun toneOf(t: String): Tone = when {
        has(t, "میترسم", "می ترسم", "نگران", "اضطراب", "استرس", "دلشوره",
            "وحشت", "بترسم", "نکند", "نکنه") -> Tone.WORRIED

        has(t, "خسته", "بریدم", "کم آورد", "نا امید", "ناامید", "دلسرد",
            "بی حوصله", "طاقتم", "دیگه نمیتونم", "بس است") -> Tone.WEARY

        has(t, "امیدوار", "امید", "منتظر", "آرزو", "دلم میخواد", "دوست دارم",
            "آرزوی", "کاش") -> Tone.HOPEFUL

        has(t, "شک", "تردید", "مطمئن نیستم", "نمیدونم", "نمی دانم",
            "دو دل", "دودل", "مردد") -> Tone.UNCERTAIN

        else -> Tone.NEUTRAL
    }

    // ── حدسِ دسته از متن (وقتی کاربر دسته‌ای انتخاب نکرده) ────────────────────

    private fun guessCategory(t: String): FalCategory = when {
        has(t, "عشق", "عاشق", "دوستم دارد", "ازدواج", "خواستگار", "نامزد",
            "همسر", "طلاق", "جدایی", "رابطه", "دل", "معشوق", "قهر") -> FalCategory.LOVE

        has(t, "کار", "شغل", "استخدام", "مصاحبه", "حقوق", "پول", "کسب",
            "شرکت", "پروژه", "معامله", "خرید", "فروش", "سرمایه",
            "بیزینس", "درس", "کنکور", "دانشگاه", "امتحان") -> FalCategory.CAREER

        has(t, "سفر", "مهاجرت", "برم", "بروم", "ویزا", "خارج", "شهر",
            "برگردم", "بازگشت", "اقامت") -> FalCategory.TRAVEL

        has(t, "سلامت", "بیمار", "مریض", "دکتر", "درمان", "عمل", "جراحی",
            "خوب میشم", "حالم", "بهبود", "دارو") -> FalCategory.HEALTH

        has(t, "تصمیم", "انتخاب", "بگیرم", "قبول کنم", "رد کنم",
            "کدام", "کدوم") -> FalCategory.DECISION

        else -> FalCategory.NONE
    }

    /** تحلیلِ پرسش. اگر متن کوتاه یا خالی باشد، [Insight.meaningful] برابرِ false است. */
    fun analyze(question: String?, chosen: FalCategory): Insight {
        val raw = question?.trim().orEmpty()
        val t = normalize(raw)
        val meaningful = t.length >= 4 && t.split(" ").size >= 2

        if (!meaningful) {
            return Insight(Shape.OPEN, Tone.NEUTRAL, chosen, false)
        }

        val category = if (chosen != FalCategory.NONE) chosen else guessCategory(t)
        return Insight(shapeOf(t), toneOf(t), category, true)
    }

    /**
     * یک جملهٔ کوتاه که نشان می‌دهد پرسش **خوانده شده** — نه صرفاً نقل شده.
     * این جمله پیش از تفسیرِ اصیلِ شعر می‌آید.
     */
    fun acknowledgement(insight: Insight, pick: (List<String>) -> String): String {
        if (!insight.meaningful) return ""

        val byShape = when (insight.shape) {
            Shape.DILEMMA -> listOf(
                "میانِ دو راه ایستاده‌ای و می‌خواهی بدانی کدام درست‌تر است.",
                "پرسشت از جنسِ انتخاب است؛ دو گزینه پیشِ روی توست."
            )
            Shape.TIMING -> listOf(
                "می‌خواهی بدانی چه وقت — و این سخت‌ترین پرسشِ فال است.",
                "پرسشت از زمان است؛ از «کِی» و «تا کِی»."
            )
            Shape.YES_NO -> listOf(
                "پاسخِ آری یا نه می‌خواهی، اما فال به زبانِ دیگری حرف می‌زند.",
                "پرسشت بسته است، ولی پاسخِ دیوان همیشه بازتر از بله و خیر است."
            )
            Shape.ABOUT_OTHER -> listOf(
                "پرسشت دربارهٔ کسِ دیگری است — و دلِ دیگران را فقط از رفتارشان می‌شود خواند.",
                "می‌خواهی از نیّتِ کسی سر دربیاوری."
            )
            Shape.GUIDANCE -> listOf(
                "دنبالِ راه می‌گردی، نه دنبالِ خبر.",
                "پرسیده‌ای چه کنی؛ این یعنی آمادهٔ عمل هستی."
            )
            Shape.OPEN -> listOf(
                "نیّتت را در دل نگه داشتی و دیوان را گشودی.",
                "پرسشت باز است و همین، جا برای پاسخِ بازتر می‌گذارد."
            )
        }

        val byTone = when (insight.tone) {
            Tone.WORRIED -> listOf("نگرانی در پرسشت پیداست.")
            Tone.WEARY -> listOf("خستگی در کلماتت هست؛ این را نادیده نمی‌گیریم.")
            Tone.HOPEFUL -> listOf("امیدی در پرسشت هست که ارزشِ نگه‌داشتن دارد.")
            Tone.UNCERTAIN -> listOf("تردید داری، و تردید نشانهٔ بی‌عقلی نیست.")
            Tone.NEUTRAL -> emptyList()
        }

        val head = pick(byShape)
        return if (byTone.isEmpty()) head else head + " " + pick(byTone)
    }

    /**
     * جملهٔ عملیِ پایانی — متناسب با شکلِ پرسش و لحن.
     * پس از تفسیرِ اصیلِ شعر می‌آید و آن را به کارِ امروزِ کاربر گره می‌زند.
     */
    fun guidance(insight: Insight, pick: (List<String>) -> String): String {
        if (!insight.meaningful) return ""

        val byShape = when (insight.shape) {
            Shape.DILEMMA -> listOf(
                "برای انتخاب، به‌جای سنجیدنِ سود و زیان، ببین کدام گزینه تو را شبیهِ آدمی می‌کند که می‌خواهی باشی.",
                "هر دو راه هزینه دارد؛ آن را بردار که هزینه‌اش را با آگاهی می‌پذیری.",
                "اگر هیچ‌کدام را نمی‌توانی انتخاب کنی، یعنی هنوز اطلاعاتِ لازم را نداری — یک هفته صبر کن و دوباره ببین."
            )
            Shape.TIMING -> listOf(
                "فال تقویم نیست؛ اما نشانه‌ها می‌گویند این کار زودتر از آنچه می‌ترسی و دیرتر از آنچه می‌خواهی رخ می‌دهد.",
                "به‌جای «کِی؟» بپرس «تا آن‌وقت چه کنم؟» — پاسخِ دوم در دستِ توست.",
                "زمان را نمی‌شود تعیین کرد، اما می‌شود آماده بود؛ آمادگی، زمان را کوتاه می‌کند."
            )
            Shape.YES_NO -> listOf(
                "فال «بله» یا «نه» نمی‌گوید؛ می‌گوید با چه نگاهی وارد شوی تا نتیجه به سودت بچرخد.",
                "پاسخ در خودِ پرسش پنهان است: اگر واقعاً نمی‌خواستی، نمی‌پرسیدی.",
                "به‌جای انتظار برای تأیید، شرط‌هایت را روشن کن؛ آن‌وقت جواب خودش پیدا می‌شود."
            )
            Shape.ABOUT_OTHER -> listOf(
                "دلِ دیگران را از حرفشان نه، از پیوستگیِ رفتارشان بخوان.",
                "به‌جای حدس‌زدنِ نیّتِ او، یک گفتگوی روشن را امتحان کن؛ حدس، رابطه را فرسوده می‌کند.",
                "تو مسئولِ سهمِ خودت در این رابطه‌ای، نه مسئولِ انتخابِ او."
            )
            Shape.GUIDANCE -> listOf(
                "کوچک‌ترین کارِ ممکن را همین امروز انجام بده؛ راه با قدم باز می‌شود نه با نقشه.",
                "یک کارِ مشخص برای این هفته بردار و بقیه را فعلاً کنار بگذار.",
                "آنچه می‌دانی باید بکنی و نمی‌کنی — همان اولین قدم است."
            )
            Shape.OPEN -> listOf(
                "این فال را به حالِ خودت گره بزن؛ معنا آنجا کامل می‌شود.",
                "چیزی از این شعر در تو تکان خورد — همان را دنبال کن.",
                "پاسخ همیشه در کلمات نیست؛ گاهی در حسی است که بعد از خواندن می‌ماند."
            )
        }

        val byTone = when (insight.tone) {
            Tone.WORRIED -> listOf(
                "و نگرانی‌ات را جدی بگیر، اما به آن اجازهٔ تصمیم‌گیری نده."
            )
            Tone.WEARY -> listOf(
                "و اگر خسته‌ای، اول استراحت کن؛ تصمیمِ آدمِ خسته معمولاً تصمیمِ خودش نیست."
            )
            Tone.HOPEFUL -> listOf(
                "و امیدت را نگه دار — اما امید را با انتظارِ منفعلانه اشتباه نگیر."
            )
            Tone.UNCERTAIN -> listOf(
                "و لازم نیست همین حالا مطمئن باشی؛ اطمینان معمولاً بعد از حرکت می‌آید."
            )
            Tone.NEUTRAL -> emptyList()
        }

        val head = pick(byShape)
        return if (byTone.isEmpty()) head else head + " " + pick(byTone)
    }
}
