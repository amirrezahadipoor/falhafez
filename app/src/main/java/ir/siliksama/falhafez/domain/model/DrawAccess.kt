package ir.siliksama.falhafez.domain.model

/**
 * حالتِ دسترسی به گرفتنِ فال.
 *
 * قاعدهٔ اقتصادیِ اپ (یک‌جا، تا هیچ صفحه‌ای منطقِ خودش را نسازد):
 *
 * | وضعیت                    | فال            | تبلیغ |
 * |--------------------------|----------------|-------|
 * | حمایت‌کننده (مشترک)      | نامحدود        | هیچ   |
 * | آفلاین                   | نامحدود        | هیچ   |
 * | آنلاین، در سهمیهٔ روزانه | ۲ فالِ رایگان  | فقط بین‌صفحه‌ای با سقفِ فرکانس |
 * | آنلاین، پس از سهمیه      | با «گشودنِ فالِ دوباره» | ویدیوی جایزه‌ای |
 *
 * اصلِ حاکم: **آفلاین‌بودن هرگز کاربر را محدود نمی‌کند.** دیوان و فال، سرمایهٔ روی
 * دستگاهِ خودِ اوست؛ تبلیغ فقط جایی معنا دارد که اینترنت هست.
 */
enum class DrawAccess {
    /** نامحدود، بدونِ تبلیغ — حمایت‌کننده. */
    UNLIMITED_SUPPORTER,

    /** نامحدود، بدونِ تبلیغ — آفلاین. */
    UNLIMITED_OFFLINE,

    /** از سهمیهٔ رایگانِ امروز استفاده می‌شود. */
    FREE_QUOTA,

    /** سهمیه تمام شده؛ فالِ بعدی نیاز به گشودن دارد. */
    NEEDS_UNLOCK;

    val isUnlimited: Boolean
        get() = this == UNLIMITED_SUPPORTER || this == UNLIMITED_OFFLINE

    /** آیا در این حالت اصلاً تبلیغی نمایش داده می‌شود؟ */
    val adsApply: Boolean
        get() = this == FREE_QUOTA || this == NEEDS_UNLOCK
}
